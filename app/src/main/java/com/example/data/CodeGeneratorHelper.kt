object CodeGeneratorHelper {

    suspend fun generateApp(
        prompt: String,
        category: String,
        enableSync: Boolean,
        enableStateMgmt: Boolean
    ): GeneratedAppResult = withContext(Dispatchers.IO) {
        val apiKey = RetrofitClient.getApiKey()
        if (apiKey.isEmpty()) {
            // High fidelity offline mock generator fallback
            return@withContext generateOfflineMock(prompt, category, enableSync, enableStateMgmt)
        }

        val systemPrompt = """
            You are Base59 Code AI companion, a master compiler and developer.
            The user wants to build an app matching: "$prompt" in category "$category".
            Real-time Sync enabled: $enableSync
            Complex State Management enabled: $enableStateMgmt
            
            Please reply strictly in this exact format with 4 distinct sections separated by '===SECTION_SEPARATOR==='.
            Format:
            [App Name]
            [App Description]
            ===SECTION_SEPARATOR===
            [Beautiful readable Kotlin code implementation of primary views in Composable]
            ===SECTION_SEPARATOR===
            [Refactored cleaner code using best practices, single responsibility, clean separation]
            ===SECTION_SEPARATOR===
            [Detailed performance & speed tips or architectural suggestions]
        """.trimIndent()

        val request = GenerateContentRequest(
            contents = listOf(
                Content(parts = listOf(Part(text = "App Prompt: $prompt\nCategory: $category")))
            ),
            generationConfig = GenerationConfig(
                temperature = 0.7f
            ),
            systemInstruction = Content(parts = listOf(Part(text = systemPrompt)))
        )

        try {
            val response = RetrofitClient.service.generateContent(apiKey, request)
            val fullText = response.candidates?.firstOrNull()?.content?.parts?.firstOrNull()?.text
            if (!fullText.isNullOrBlank()) {
                val sections = fullText.split("===SECTION_SEPARATOR===")
                val meta = sections.getOrNull(0)?.trim()?.lines() ?: emptyList()
                val name = meta.getOrNull(0)?.replace("[", "")?.replace("]", "")?.trim() ?: "${category} App"
                val description = meta.drop(1).joinToString("\n").replace("[", "")?.replace("]", "")?.trim() ?: "Generated by Base59 AI"
                val code = sections.getOrNull(1)?.trim() ?: "// Code generated successfully."
                val refactoredCode = sections.getOrNull(2)?.trim() ?: "// Refactored source."
                val performanceNotes = sections.getOrNull(3)?.trim() ?: "- Verified performance guidelines."
                
                return@withContext GeneratedAppResult(
                    name = name,
                    category = category,
                    description = description,
                    code = code,
                    refactoredCode = refactoredCode,
                    performanceNotes = performanceNotes,
                    hasSync = enableSync,
                    hasStateMgmt = enableStateMgmt
                )
            }
        } catch (e: Exception) {
            // Log or ignore to fallback
        }

        return@withContext generateOfflineMock(prompt, category, enableSync, enableStateMgmt)
    }

    private fun generateOfflineMock(
        prompt: String,
        category: String,
        enableSync: Boolean,
        enableStateMgmt: Boolean
    ): GeneratedAppResult {
        val appName = if (prompt.length < 15) prompt.capitalize() else "Custom ${category} Manager"
        val description = "A modern $category custom starter template optimized to run with advanced code architecture and offline synchronization schemas."

        val (code, refactored, suggestions) = when (category.lowercase()) {
            "ecommerce" -> getEcommerceCode(enableSync, enableStateMgmt)
            "social" -> getSocialCode(enableSync, enableStateMgmt)
            else -> getProductivityCode(enableSync, enableStateMgmt)
        }

        return GeneratedAppResult(
            name = appName,
            category = category,
            description = description,
            code = code,
            refactoredCode = refactored,
            performanceNotes = suggestions,
            hasSync = enableSync,
            hasStateMgmt = enableStateMgmt
        )
    }

